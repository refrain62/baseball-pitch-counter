"use strict";

const CACHE_NAME = "pitch-counter-shell-v2";
const APP_SHELL = [
  "/counter/",
  "/counter/index.html",
  "/counter/counter.css",
  "/counter/counter.js",
  "/counter/manifest.webmanifest",
  "/counter/icons/icon-192.png",
  "/counter/icons/icon-512.png",
  "/counter/icons/icon-maskable-512.png",
  "/counter/icons/apple-touch-icon.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith("/counter/")) return;

  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          void caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(async () => {
        const cached = await caches.match(request);
        if (cached) return cached;
        if (request.mode === "navigate") return caches.match("/counter/index.html");
        throw new Error("Offline and not cached");
      })
  );
});
